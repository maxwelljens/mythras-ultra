// Package resolve is the single mutation entry point for game state: every
// mechanical change to a session runs as a typed [Move] through [Apply],
// which validates before mutating, keeps the dice audit, and persists the
// live RNG stream into the state so a resumed session continues the same
// random sequence (ARCHITECTURE.md §4.5, §3.1).
//
// The package sequences and audits; the mechanics live in the engine
// subpackages (char, rules, combat, world, dice) that the moves call. No
// code here reads a clock or a non-deterministic source: CreatedAt,
// UpdatedAt and wall time belong to the caller and the persistence layer.
package resolve

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/mythras-ultra/myul/internal/engine/char"
	"github.com/mythras-ultra/myul/internal/engine/combat"
	"github.com/mythras-ultra/myul/internal/engine/dice"
	"github.com/mythras-ultra/myul/internal/engine/world"
)

// SchemaVersion is the state schema this build reads and writes. The
// persistence layer refuses to load a state.json carrying any other version
// rather than reinterpret unknown fields (state.ErrSchemaVersion).
const SchemaVersion = 1

// Scene is the narrative frame the GM last established: where play happens,
// a description, and free-text labels for who or what is present. It carries
// no mechanics — present entries are labels (typically character IDs), not
// validated references.
type Scene struct {
	// Location is where play is happening.
	Location string `json:"location,omitempty"`
	// Description is the GM's scene-setting text.
	Description string `json:"description,omitempty"`
	// Present lists who or what is on stage, in free text.
	Present []string `json:"present,omitempty"`
}

// State is the complete, JSON-round-trippable aggregate of one play
// session: identity, characters (PCs and NPCs alike — the char.Character.PC
// flag distinguishes them), the world, the running encounter, the scene,
// recaps, the monotonic move counter and the persisted RNG stream.
//
// The zero value is not usable; create one with [NewState] or unmarshal a
// persisted state and call [State.Normalize].
type State struct {
	// SchemaVersion is the persistence schema version ([SchemaVersion]).
	SchemaVersion int `json:"schemaVersion"`
	// ID is the session identifier (filesystem-safe, engine-generated by
	// [NewState]); the persistence layer keys sessions by it.
	ID string `json:"id"`
	// Name is what the session is called.
	Name string `json:"name"`
	// Seed is the session RNG seed: dice.NewRand(Seed) reproduces every
	// roll from the start of the session.
	Seed int64 `json:"seed"`
	// CreatedAt and UpdatedAt are session timestamps. The engine never
	// reads them and never stamps them — the caller and the persistence
	// layer own wall time.
	CreatedAt time.Time `json:"createdAt"`
	UpdatedAt time.Time `json:"updatedAt"`
	// Characters holds every character in play — PCs and NPCs alike (the
	// PC flag distinguishes them), keyed by engine ID.
	Characters map[string]*char.Character `json:"characters"`
	// World is the campaign's setting state; [NewState] initialises it.
	World *world.World `json:"world,omitempty"`
	// Encounter is the running fight, or nil outside combat. Its
	// Participants point at the same instances held in Characters —
	// [State.Normalize] re-binds that identity after a JSON load.
	Encounter *combat.Encounter `json:"encounter,omitempty"`
	// LastAttack is the attack exchange [ResolveAttack] resolved most
	// recently, retained so [ApplySpecialEffect] can adjust that specific
	// exchange. It is cleared when an encounter starts and ends. The
	// pre-wound rollback snapshot inside combat.AttackResult is
	// deliberately unexported by combat and therefore not persisted — after
	// a load, effects that reverse a whole blow run without it.
	LastAttack *combat.AttackResult `json:"lastAttack,omitempty"`
	// Scene is the current narrative frame.
	Scene Scene `json:"scene"`
	// Recaps are the stored end-of-session summaries, oldest first
	// (context rebuild input for the harness).
	Recaps []string `json:"recaps,omitempty"`
	// EventSeq counts accepted moves; [Apply] increments it. Failed moves
	// leave it untouched.
	EventSeq uint64 `json:"eventSeq"`
	// RNGState is the persisted position of the session's dice stream —
	// the marshalled *dice.Rand written by [Apply] after every accepted
	// move. A resumed session restores it, so rolls continue exactly where
	// the previous process stopped. Empty before the first move.
	RNGState []byte `json:"rngState,omitempty"`

	// rng is the live dice source, lazily restored from RNGState (see
	// State.Rand). Unexported: the stream position lives in RNGState.
	rng *dice.Rand
}

// NewState returns a session ready for its first move: schema version and
// ID set, Characters initialised, a fresh world, and the RNG seeded with
// seed. A zero seed is replaced by one drawn from the operating system's
// entropy source ([dice.NewRandFromEntropy]) — the chosen seed is recorded
// in State.Seed, which is what makes the session replayable. CreatedAt and
// UpdatedAt stay zero: the engine never reads clocks.
func NewState(name string, seed int64) *State {
	if seed == 0 {
		_, seed = dice.NewRandFromEntropy()
	}
	return &State{
		SchemaVersion: SchemaVersion,
		ID:            newSessionID(seed),
		Name:          name,
		Seed:          seed,
		Characters:    make(map[string]*char.Character),
		World:         world.New(name, ""),
	}
}

// newSessionID mints a filesystem-safe session identifier from
// cryptographic entropy — never from the session RNG, whose stream must stay
// purely a function of State.Seed for replay. The seed is a deterministic
// fallback for the documented never-failing crypto/rand.Read.
func newSessionID(seed int64) string {
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		return fmt.Sprintf("s-%016x", uint64(seed))
	}
	return "s-" + hex.EncodeToString(b[:])
}

// Rand returns the session's live dice source. The stream is restored from
// the persisted RNGState when present — a resumed session continues the same
// sequence — and otherwise created from State.Seed. [State.Normalize] (run by
// the persistence layer on load) rejects corrupt RNGState up front, so the
// fallback only ever applies to hand-built states.
func (s *State) Rand() *dice.Rand {
	if s.rng != nil {
		return s.rng
	}
	if len(s.RNGState) > 0 {
		if r, err := dice.UnmarshalRandBinary(s.RNGState); err == nil {
			s.rng = r
			return s.rng
		}
	}
	s.rng = dice.NewRand(s.Seed)
	return s.rng
}

// Normalize re-binds state identity after deserialisation. JSON decoding
// gives combat.Encounter.Participants their own copies of the characters;
// Normalize replaces each with the canonical *char.Character instance held in
// State.Characters so pointer identity holds again ("the resolve layer owns
// their lifecycle" — combat.Encounter). It also validates the encounter's
// structural references (participant IDs present, order and counter indices
// in range, AP parallel to Participants) so a corrupt file is refused with an
// error instead of panicking a later operation, verifies the persisted RNG
// stream, and initialises a nil Characters map.
//
// Errors wrap [ErrDanglingParticipant] or [ErrInvalidState]; a State that
// loaded cleanly normalises to the identity it had before the round trip.
func (s *State) Normalize() error {
	if s == nil {
		return fmt.Errorf("%w: nil state", ErrInvalidState)
	}
	if s.Characters == nil {
		s.Characters = make(map[string]*char.Character)
	}
	if len(s.RNGState) > 0 {
		if _, err := dice.UnmarshalRandBinary(s.RNGState); err != nil {
			return fmt.Errorf("%w: persisted RNG stream is unreadable: %w", ErrInvalidState, err)
		}
	}
	e := s.Encounter
	if e == nil {
		return nil
	}
	for i, p := range e.Participants {
		if p == nil {
			return fmt.Errorf("%w: participant %d is nil", ErrDanglingParticipant, i)
		}
		if p.ID == "" {
			return fmt.Errorf("%w: participant %d (%q) has no ID to re-bind with", ErrDanglingParticipant, i, p.Name)
		}
		canonical, ok := s.Characters[p.ID]
		if !ok || canonical == nil {
			return fmt.Errorf("%w: participant %q is not in characters", ErrDanglingParticipant, p.ID)
		}
		e.Participants[i] = canonical
	}
	if len(e.AP) != len(e.Participants) {
		return fmt.Errorf("%w: encounter AP slice (%d) does not match participants (%d)",
			ErrInvalidState, len(e.AP), len(e.Participants))
	}
	for _, o := range e.Order {
		if o.Index < 0 || o.Index >= len(e.Participants) {
			return fmt.Errorf("%w: strike order references participant index %d of %d",
				ErrInvalidState, o.Index, len(e.Participants))
		}
	}
	for _, c := range e.Counters {
		if c.Index < 0 || c.Index >= len(e.Participants) {
			return fmt.Errorf("%w: counter references participant index %d of %d",
				ErrInvalidState, c.Index, len(e.Participants))
		}
	}
	return nil
}

// characterIDs returns every character ID, sorted, for lookup-error
// messages and identifier minting.
func (s *State) characterIDs() []string {
	ids := make([]string, 0, len(s.Characters))
	for id := range s.Characters {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	return ids
}

// character resolves id to its canonical character. An unknown or nil entry
// errors wrapping [ErrUnknownCharacter], listing the known IDs so the harness
// can answer IMPOSSIBLE with real choices (harness-surface.md, IDs).
func (s *State) character(id string) (*char.Character, error) {
	c, ok := s.Characters[id]
	if !ok || c == nil {
		return nil, fmt.Errorf("%w %q (known: %s)", ErrUnknownCharacter, id, strings.Join(s.characterIDs(), ", "))
	}
	return c, nil
}

// encounter returns the live encounter or an error wrapping
// [ErrNoEncounter]. Combat moves validate through it before touching
// combat APIs, so a nil encounter becomes a structured refusal rather than a
// dereference.
func (s *State) encounter() (*combat.Encounter, error) {
	if s.Encounter == nil {
		return nil, ErrNoEncounter
	}
	return s.Encounter, nil
}

// participantIndex returns c's position in the encounter's participant list,
// or -1 when it is not fighting (identity is the pointer — Normalize keeps
// participants canonical).
func participantIndex(e *combat.Encounter, c *char.Character) int {
	for i, p := range e.Participants {
		if p == c {
			return i
		}
	}
	return -1
}
